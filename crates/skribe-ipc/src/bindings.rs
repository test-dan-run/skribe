//! Generates the TypeScript side of the command contract and checks that the committed copy
//! in `src/ipc/generated` matches. Run `npm run ipc:generate` to rewrite it after a change.

use std::collections::{BTreeMap, BTreeSet};
use std::fs;
use std::path::{Path, PathBuf};

use ts_rs::{Config, TS};

use crate::library::{LibraryStatus, RestoreSnapshotArgs};
use crate::{COMMAND_NAMES, CommandError};

const UPDATE_VARIABLE: &str = "SKRIBE_UPDATE_IPC";
const HEADER: &str = "// This file was generated by skribe-ipc. Do not edit this file manually.\n";

struct CommandSpec {
    name: &'static str,
    /// TypeScript type of the single `args` parameter, when the command takes one.
    args: Option<String>,
    result: String,
}

fn config(out_dir: &Path) -> Config {
    // Timestamps and sizes stay far below 2^53, so they are plain numbers in TypeScript.
    Config::new().with_out_dir(out_dir).with_large_int("number")
}

fn command_specs(cfg: &Config) -> Vec<CommandSpec> {
    let status = LibraryStatus::name(cfg);
    vec![
        CommandSpec {
            name: "library_status",
            args: None,
            result: status.clone(),
        },
        CommandSpec {
            name: "library_retry_open",
            args: None,
            result: status.clone(),
        },
        CommandSpec {
            name: "library_restore_snapshot",
            args: Some(RestoreSnapshotArgs::name(cfg)),
            result: status,
        },
    ]
}

/// File name to contents for everything in `src/ipc/generated`.
fn generate() -> BTreeMap<String, String> {
    let scratch = tempfile::tempdir().expect("temporary folder");
    let cfg = config(scratch.path());
    LibraryStatus::export_all(&cfg).expect("export LibraryStatus");
    RestoreSnapshotArgs::export_all(&cfg).expect("export RestoreSnapshotArgs");
    CommandError::export_all(&cfg).expect("export CommandError");

    let mut files = read_typescript(scratch.path());
    let type_names: Vec<String> = files
        .keys()
        .map(|file| file.trim_end_matches(".ts").to_owned())
        .collect();

    let specs = command_specs(&cfg);
    let mut imports = BTreeSet::new();
    let mut entries = String::new();
    for spec in &specs {
        imports.insert(spec.result.clone());
        imports.extend(spec.args.clone());
        let args = spec.args.as_deref().unwrap_or("null");
        entries.push_str(&format!(
            "  {}: {{ args: {args}; result: {} }};\n",
            spec.name, spec.result
        ));
    }
    let mut commands = String::from(HEADER);
    for import in &imports {
        commands.push_str(&format!(
            "import type {{ {import} }} from \"./{import}\";\n"
        ));
    }
    commands.push_str(
        "\n/**\n * Every command the app exposes. A command with `args: null` takes none. \
         Every command\n * rejects with a `CommandError`.\n */\n",
    );
    commands.push_str(&format!("export type Commands = {{\n{entries}}};\n"));
    files.insert("commands.ts".to_owned(), commands);

    let mut index = String::from(HEADER);
    for name in &type_names {
        index.push_str(&format!("export type {{ {name} }} from \"./{name}\";\n"));
    }
    index.push_str("export type { Commands } from \"./commands\";\n");
    files.insert("index.ts".to_owned(), index);
    files
}

fn read_typescript(dir: &Path) -> BTreeMap<String, String> {
    let mut files = BTreeMap::new();
    for entry in fs::read_dir(dir).expect("list generated folder") {
        let path = entry.expect("entry").path();
        if path.extension().is_some_and(|extension| extension == "ts") {
            let name = path
                .file_name()
                .expect("file name")
                .to_string_lossy()
                .into_owned();
            let contents = fs::read_to_string(&path).expect("read generated file");
            files.insert(name, contents.replace("\r\n", "\n"));
        }
    }
    files
}

fn repository_root() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).join("..").join("..")
}

#[test]
fn committed_typescript_matches_the_rust_contract() {
    let generated = generate();
    let committed_dir = repository_root().join("src").join("ipc").join("generated");

    if std::env::var_os(UPDATE_VARIABLE).is_some() {
        fs::create_dir_all(&committed_dir).expect("create generated folder");
        for stale in read_typescript(&committed_dir)
            .keys()
            .filter(|name| !generated.contains_key(*name))
        {
            fs::remove_file(committed_dir.join(stale)).expect("remove stale file");
        }
        for (name, contents) in &generated {
            fs::write(committed_dir.join(name), contents).expect("write generated file");
        }
        return;
    }

    let committed = read_typescript(&committed_dir);
    assert!(
        committed == generated,
        "src/ipc/generated is out of date with skribe-ipc. Run `npm run ipc:generate` and \
         commit the result.\ncommitted files: {:?}\ngenerated files: {:?}",
        committed.keys().collect::<Vec<_>>(),
        generated.keys().collect::<Vec<_>>(),
    );
}

#[test]
fn the_command_list_matches_the_generated_command_map() {
    let scratch = tempfile::tempdir().expect("temporary folder");
    let specs = command_specs(&config(scratch.path()));
    let names: Vec<&str> = specs.iter().map(|spec| spec.name).collect();
    assert_eq!(names, COMMAND_NAMES);
}

/// The capability file must grant the window exactly the app's commands and nothing else:
/// no file system, shell, HTTP, opener or other plugin permission.
#[test]
fn the_window_capability_grants_exactly_the_app_commands() {
    let path = repository_root()
        .join("src-tauri")
        .join("capabilities")
        .join("default.json");
    let text = fs::read_to_string(&path).expect("read capability file");
    let capability: serde_json::Value = serde_json::from_str(&text).expect("capability is JSON");

    let mut granted: Vec<String> = capability["permissions"]
        .as_array()
        .expect("permissions is a list")
        .iter()
        .map(|permission| {
            permission
                .as_str()
                .expect("permission is a plain name")
                .to_owned()
        })
        .collect();
    granted.sort();
    let mut expected: Vec<String> = COMMAND_NAMES
        .iter()
        .map(|name| format!("allow-{}", name.replace('_', "-")))
        .collect();
    expected.sort();

    assert_eq!(granted, expected);
    assert!(
        capability.get("remote").is_none(),
        "no remote origin may call commands"
    );
}
